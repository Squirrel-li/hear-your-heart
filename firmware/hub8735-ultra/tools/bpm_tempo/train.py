"""Train the bpm_tempo candidate scorer and export it as C (bpm_tempo_model.h).

Input: features.tsv from dump.cpp (path, candidate bpm, features...) and refs.tsv (path, reference bpm).
A candidate is "correct" when it is within 4% of the reference. Tracks are weighted so that rare
BPM ranges count more (weight ~ 1/sqrt(range size)); the HUB picks the highest-scoring candidate.
Usage: python train.py features.tsv refs.tsv ../../application/embedded_loudspeaker/bpm_tempo_model.h
Needs numpy and scikit-learn (tested with 1.4).
"""
import sys
import numpy as np
from sklearn.ensemble import HistGradientBoostingClassifier

RANGES = ((0, 70), (70, 90), (90, 110), (110, 130), (130, 150), (150, 170), (170, 1000))
PARAMS = dict(max_iter=300, learning_rate=0.05, max_leaf_nodes=15, random_state=0)


def load(features_path, refs_path=None):
    """-> (paths, groups, bpm, X, ref per row or None). Tracks with no candidates are skipped."""
    refs = dict((p, float(r)) for p, r in (l.rstrip("\n").split("\t")[:2] for l in open(refs_path))) if refs_path else {}
    paths, rows, bpm = [], [], []
    for line in open(features_path):
        f = line.rstrip("\n").split("\t")
        if len(f) < 3 or (refs_path and f[0] not in refs):
            continue
        paths.append(f[0]); bpm.append(float(f[1])); rows.append([float(v) for v in f[2:]])
    names = sorted(set(paths), key=paths.index)
    index = {p: i for i, p in enumerate(names)}
    g = np.array([index[p] for p in paths])
    ref = np.array([refs[p] for p in names]) if refs_path else None
    return names, g, np.array(bpm), np.array(rows, dtype=np.float32), ref


def ok(est, ref):
    return np.abs(est - ref) <= 0.04 * ref


def fit(X, g, bpm, ref, p=0.5):
    y = ok(bpm, ref[g])
    rid = np.array([next(j for j, (lo, hi) in enumerate(RANGES) if lo <= r < hi) for r in ref])
    w = (1.0 / np.bincount(rid, minlength=len(RANGES))[rid]) ** p
    w /= w.mean()
    return HistGradientBoostingClassifier(**PARAMS).fit(X, y, sample_weight=w[g])


def pick(clf, X, g, bpm, n):
    s = clf.decision_function(X)
    out = np.zeros(n)
    best = np.full(n, -np.inf)
    for i, (gi, si) in enumerate(zip(g, s)):
        if si > best[gi]:
            best[gi], out[gi] = si, bpm[i]
    return out


def export(clf, path, nfeat):
    nodes, roots = [], []
    for it in clf._predictors:
        tree = it[0].nodes
        base = len(nodes)
        roots.append(base)
        for nd in tree:
            if nd["is_leaf"]:
                nodes.append((-1, 0, 0, float(nd["value"])))
            else:
                nodes.append((int(nd["feature_idx"]), base + int(nd["left"]), base + int(nd["right"]), float(nd["num_threshold"])))
    assert len(nodes) < 65536
    base = float(np.ravel(clf._baseline_prediction)[0])
    with open(path, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/bpm_tempo/train.py; do not edit.\n#ifndef BPM_TEMPO_MODEL_H\n#define BPM_TEMPO_MODEL_H\n\n")
        f.write("#include <stdint.h>\n\nnamespace bpm_tempo {\n\n")
        f.write(f"constexpr int MODEL_FEATURES = {nfeat};\nconstexpr int MODEL_TREES = {len(roots)};\nconstexpr float MODEL_BASE = {base!r}f;\n\n")
        f.write("// feature < 0: leaf with value; otherwise go to left when x <= value.\n")
        f.write("struct ModelNode { int16_t feature; uint16_t left, right; float value; };\n\n")
        f.write(f"const ModelNode MODEL_NODES[{len(nodes)}] = {{\n")
        for a, b, c, v in nodes:
            lit = f"{v:.9g}"
            lit += "" if any(ch in lit for ch in ".en") else ".0"  # "8f" is not a valid C++ float literal
            f.write(f"    {{{a}, {b}, {c}, {lit}f}},\n")
        f.write("};\n\n")
        f.write(f"const uint16_t MODEL_ROOTS[{len(roots)}] = {{" + ", ".join(map(str, roots)) + "};\n\n")
        f.write("}  // namespace bpm_tempo\n\n#endif\n")


def main():
    names, g, bpm, X, ref = load(sys.argv[1], sys.argv[2])
    clf = fit(X, g, bpm, ref)
    est = pick(clf, X, g, bpm, len(names))
    print(f"{len(names)} tracks, training Acc1 {100 * ok(est, ref).mean():.1f}%")
    export(clf, sys.argv[3], X.shape[1])
    # Self-check: the exported trees reproduce sklearn's scores.
    nodes, roots, base = _parse(sys.argv[3])
    for i in range(0, len(X), max(1, len(X) // 200)):
        s = base
        for r in roots:
            n = r
            while nodes[n][0] >= 0:
                n = nodes[n][1] if X[i, nodes[n][0]] <= nodes[n][3] else nodes[n][2]
            s += nodes[n][3]
        assert abs(s - clf.decision_function(X[i:i + 1])[0]) < 1e-3, i
    print("exported", sys.argv[3])


def _parse(path):
    txt = open(path, encoding="utf-8").read()
    body = txt[txt.index("MODEL_NODES"):txt.index("MODEL_ROOTS")]
    nodes = []
    for l in body.splitlines():
        l = l.strip()
        if l.startswith("{") and l.endswith("},"):
            a, b, c, v = l[1:-2].split(", ")
            nodes.append((int(a), int(b), int(c), np.float32(float(v.rstrip("f")))))
    roots = [int(x) for x in txt[txt.index("MODEL_ROOTS"):].split("{")[1].split("}")[0].split(", ")]
    base = float(txt.split("MODEL_BASE = ")[1].split("f;")[0])
    return nodes, roots, base


if __name__ == "__main__":
    main()
