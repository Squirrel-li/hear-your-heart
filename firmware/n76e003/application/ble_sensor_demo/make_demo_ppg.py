"""Turn a recorded BMH08002-4 CSV (elapsed_s, status, ir_ppg, red_ppg) or a ble_capture.html
*_raw.json export into source/demo_ppg.h.

Stores every pair of samples as one averaged point (35.7 Hz -> 17.9 Hz), as int8 steps per channel
in units of 2^shift (the smallest shift that fits the largest step of that channel). The firmware
plays it back at 28 ms per sample with linear interpolation and loops. Then it checks, with gcc and
the real ppg_motion_hr.h (ACC not required, like the DEMO), that the played-back loop still gives
about the HR of the original recording.

    python make_demo_ppg.py RECORDING.csv --start 20 --seconds 22
"""
import argparse
import csv
import json
import subprocess
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
HR_SRC = HERE.parent / 'ble_sensor_hr' / 'source'
TICK_MS = 28
WRAPPER = r'''
#include <stdio.h>
#include "ppg_motion_hr.h"
int main(void) {
    motion_hr h; unsigned t, a, b, st;
    mh_reset(&h, 0);
    while (scanf("%u %u %u %u", &t, &a, &b, &st) == 4)
        if (mh_ppg(&h, (uint16_t)a, (uint16_t)b, (uint16_t)t, (uint8_t)st)) printf("%u %u\n", t, h.bpm);
    return 0;
}
'''


def encode(points, shift):
    """int8 steps (x 2^shift) that follow the points, then return exactly to the first one (loop seam)."""
    rec = [list(points[0])]
    steps = []
    targets = points[1:] + [points[0]]
    i = 0
    while i < len(targets) or rec[-1] != list(points[0]):
        goal = targets[min(i, len(targets) - 1)]
        d = [max(-127, min(127, round((goal[c] - rec[-1][c]) / (1 << shift[c])))) for c in (0, 1)]
        steps.append(d)
        rec.append([rec[-1][c] + (d[c] << shift[c]) for c in (0, 1)])
        i += 1
    return steps, rec[:-1]


def play(start, steps, shift, loops):
    """Exactly what demo_task() emits: point, then point + (step >> 1)."""
    out = []
    for _ in range(loops):
        cur = list(start)
        for d in steps:
            d = [d[c] << shift[c] for c in (0, 1)]
            out.append(tuple(cur))
            out.append(tuple(cur[c] + (d[c] >> 1) for c in (0, 1)))
            cur = [cur[c] + d[c] for c in (0, 1)]
        assert cur == list(start), 'loop does not close'
    return out


def hr(exe, samples):
    text = ''.join(f'{(i * TICK_MS) & 0xFFFF} {a} {b} 2\n' for i, (a, b) in enumerate(samples))
    rows = subprocess.run([str(exe)], input=text, text=True, capture_output=True, check=True).stdout.split()
    return [int(v) for v in rows[1::2]]


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('csv', type=Path)
    p.add_argument('--start', type=float, default=0.0, help='seconds into the recording')
    p.add_argument('--seconds', type=float, required=True)
    p.add_argument('--out', type=Path, default=HERE / 'source' / 'demo_ppg.h')
    a = p.parse_args()

    if a.csv.suffix == '.json':             # ble_capture.html "raw" export; elapsed_s made relative to the first PPG
        with a.csv.open() as f:
            ppg = [r['sample'] for r in json.load(f)['records'] if r['sample']['kind'] == 'ppg']
        t0 = ppg[0]['elapsed_s']
        rows = [{'elapsed_s': s['elapsed_s'] - t0, 'status': str(s['status']), 'ir_ppg': s['ir_ppg'],
                 'red_ppg': s['red_ppg']} for s in ppg]
        if any(s['seq_gap'] for s in ppg):
            raise SystemExit('recording has sequence gaps')
    else:
        with a.csv.open(newline='') as f:
            rows = list(csv.DictReader(f))
    rows = [r for r in rows if a.start <= float(r['elapsed_s']) < a.start + a.seconds]
    if len(rows) < 200:
        raise SystemExit(f'only {len(rows)} samples in that range')
    if any(r['status'] != '2' for r in rows):
        raise SystemExit('range contains samples with status != 2 (no finger / no data); pick a clean range')
    raw = [(int(r['ir_ppg']), int(r['red_ppg'])) for r in rows]
    raw = raw[:len(raw) // 2 * 2]
    points = [tuple((raw[i][c] + raw[i + 1][c]) // 2 for c in (0, 1)) for i in range(0, len(raw), 2)]
    shift = [0, 0]
    for c in (0, 1):
        big = max(abs(points[k + 1][c] - points[k][c]) for k in range(len(points) - 1))
        while big > 127 << shift[c]:
            shift[c] += 1
    steps, rec = encode(points, shift)
    err = max(abs(rec[k][c] - points[k][c]) for k in range(len(points)) for c in (0, 1))

    with tempfile.TemporaryDirectory() as tmp:
        c, exe = Path(tmp) / 'hr.c', Path(tmp) / 'hr.exe'
        c.write_text(WRAPPER)
        subprocess.run(['gcc', '-std=c99', '-O2', '-I' + str(HR_SRC), str(c), '-o', str(exe)], check=True)
        original = hr(exe, raw)
        played = hr(exe, play(points[0], steps, shift, 3))

    flat = ','.join(f'{d[0]},{d[1]}' for d in steps)
    a.out.write_text(
        f'/* Generated by ../make_demo_ppg.py from {a.csv.name}, {a.start:g} s + {a.seconds:g} s; do not edit. */\n'
        f'/* {len(steps)} points at {2 * TICK_MS} ms (IR, red int8 steps x 2^shift), loops back to the first. */\n'
        f'#define DEMO_N          {len(steps)}\n'
        f'#define DEMO_IR0        {points[0][0]}\n'
        f'#define DEMO_RED0       {points[0][1]}\n'
        f'#define DEMO_IR_SHIFT   {shift[0]}\n'
        f'#define DEMO_RED_SHIFT  {shift[1]}\n'
        f'__code const signed char demo_ppg[DEMO_N * 2] = {{\n{flat}\n}};\n')
    print(f'{a.out}: {len(steps)} points, {2 * len(steps)} B, loop {len(steps) * 2 * TICK_MS / 1000:.1f} s, '
          f'shift IR {shift[0]} red {shift[1]}, max error {err} counts')
    print('HR original    :', original)
    print('HR played (x3) :', played)


if __name__ == '__main__':
    main()
